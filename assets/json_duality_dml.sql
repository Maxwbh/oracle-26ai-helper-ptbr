/*
ANTI-PATTERN 1: "UPDATE parcial" enviando documento incompleto
  -- ERRADO: SET data = '{"_id":2, "_metadata":{...}, "nome":"X"}'
  -- Um UPDATE com documento substitui o documento inteiro e não pode
  -- remover campos definidos pela view.
  -- CERTO: documento completo (lido e alterado) ou JSON_TRANSFORM.

ANTI-PATTERN 2: UPDATE sem ETAG em ambiente concorrente
  -- Documento sem _metadata.etag (ou JSON_TRANSFORM direto) não tem
  -- verificação de ETAG → risco de lost update.
  -- BOM: ler → alterar cópia → gravar documento com o etag lido; tratar ORA-42699.

ANTI-PATTERN 3: Reusar ETAG antigo
  - O ETAG muda sempre que o conteúdo "checável" muda; releia antes de nova
    tentativa.

ANTI-PATTERN 4: DELETE com COMMIT por linha
  -- RUIM:
  FOR r IN (...) LOOP
    DELETE FROM departamentos_dv d WHERE d.data."_id" = r.id;
    COMMIT;
  END LOOP;
  -- BOM: uma instrução por lote, um COMMIT controlado pelo chamador.

ANTI-PATTERN 5: Nova tentativa infinita em ETAG divergente
  - Poucas tentativas (3 a 5) com backoff; acima disso há linha muito
    disputada e o desenho precisa ser revisto.

ANTI-PATTERN 6: Citar código de erro errado no tratamento
  - ORA-42699 = ETAG divergente          - ORA-40940 = campo NOUPDATE
  - ORA-42605 = mesma linha alterada >1x - ORA-42692 = erro de DML na tabela-base
  - ORA-42693 = (criação) tabela dependente não pode ser DELETE
  - ORA-42624 = coluna inválida no ORDER BY - ORA-40769 = valor não é array JSON
*/

