--==============================================================================
-- 1. INSERT — cria linhas nas tabelas-base a partir do JSON
--==============================================================================

-- Insert simples — só departamento (sem funcionários)
INSERT INTO departamentos_dv VALUES ('
{
  "nome"        : "Genética Forense",
  "localizacao" : "Bloco D"
}');

-- Insert com array — departamento + funcionários (FK preenchida pela view)
INSERT INTO departamentos_dv VALUES ('
{
  "nome"        : "DNA Forense",
  "localizacao" : "Bloco D",
  "funcionarios": [
    {"nome": "Lucas Pereira", "cargo": "Geneticista", "salario": 14000},
    {"nome": "Carla Mendes",  "cargo": "Auxiliar",    "salario": 4800}
  ]
}');

-- Insert SEM _id: a chave vem da identity (GENERATED BY DEFAULT ON NULL)
-- Insert COM _id já existente: violação da PK da tabela raiz (erro de
--   constraint). A pilha costuma trazer ORA-42692 (erro de DML na tabela-base)
--   seguido do erro da constraint.
--   -- A VERIFICAR: pilha exata de erros para PK duplicada via duality view.
-- Um _metadata enviado no INSERT é ignorado.

COMMIT;


--==============================================================================
-- 2. UPDATE de documento INTEIRO — com ETAG (controle otimista)
--
-- O documento enviado SUBSTITUI o atual. Um update não pode acrescentar nem
-- remover campos definidos pela view: envie o documento completo, de
-- preferência partindo do que foi lido (fetch → altera cópia local → grava).
-- Se o documento trouxer _metadata.etag, o banco compara com o estado atual;
-- divergência → ORA-42699.
--==============================================================================

-- 1. Ler o documento (o ETAG atual vem em _metadata.etag)
SELECT JSON_SERIALIZE(d.data PRETTY)
  FROM departamentos_dv d
 WHERE d.data."_id" = 1;

-- Lê o ETAG atual do documento (SQL*Plus/SQLcl: variável de ligação)
VARIABLE etag_lido VARCHAR2(64)
BEGIN
  SELECT JSON_VALUE(d.data, '$._metadata.etag')
    INTO :etag_lido
    FROM departamentos_dv d
   WHERE d.data."_id" = 1;
END;
/

-- 2. Gravar o documento completo com o ETAG lido
UPDATE departamentos_dv d
   SET d.data = '{
     "_id"        : 1,
     "_metadata"  : {"etag": "' || :etag_lido || '"},
     "nome"       : "Necropsia Especializada",
     "localizacao": "Bloco A - Térreo",
     "funcionarios": [
       {"idFuncionario": 1, "nome": "João Silva", "cargo": "Médico Legista Sênior", "salario": 16500},
       {"idFuncionario": 2, "nome": "Ana Costa",  "cargo": "Auxiliar Sênior",       "salario": 5500}
     ]
   }'
 WHERE d.data."_id" = 1;

COMMIT;

-- ETAG divergente (alguém alterou entre a leitura e a gravação):
--   ORA-42699: Cannot update JSON Relational Duality View 'DEPARTAMENTOS_DV':
--   The ETAG of document with ID '...' in the database did not match the
--   ETAG passed in.
-- Solução: reler (novo ETAG) e tentar de novo — padrão na seção 6.


--==============================================================================
-- 3. UPDATE PARCIAL — JSON_TRANSFORM
--
-- Altera só os campos indicados; o restante do documento é preservado.
-- ATENÇÃO: em update parcial o etag NÃO é enviado, logo NÃO há comparação de
-- ETAG — não existe controle otimista de concorrência nesse caminho.
--==============================================================================

UPDATE departamentos_dv d
   SET d.data = JSON_TRANSFORM(d.data, SET '$.nome' = 'Toxicologia Avançada')
 WHERE d.data."_id" = 2;

-- Resultado: apenas "nome" alterado; "localizacao" e "funcionarios" preservados.
-- Operação de array do JSON_TRANSFORM sobre valor que não é array: ORA-40769.


--==============================================================================
-- 4. UPDATE em sub-array — incluir/remover funcionário
--
-- Um update pode inserir/excluir elementos de um array (desde que a tabela
-- filha tenha as anotações INSERT/DELETE na view).
--==============================================================================

-- Incluir funcionário: documento completo, novo elemento sem idFuncionario
-- (a identity gera a chave). Comentários não são permitidos dentro do JSON.
-- Lê o ETAG atual do documento (SQL*Plus/SQLcl: variável de ligação)
BEGIN
  SELECT JSON_VALUE(d.data, '$._metadata.etag')
    INTO :etag_lido
    FROM departamentos_dv d
   WHERE d.data."_id" = 1;
END;
/

UPDATE departamentos_dv d
   SET d.data = '{
     "_id"      : 1,
     "_metadata": {"etag": "' || :etag_lido || '"},
     "nome"       : "Necropsia Especializada",
     "localizacao": "Bloco A - Térreo",
     "funcionarios": [
       {"idFuncionario": 1, "nome": "João Silva", "cargo": "Médico Legista", "salario": 16500},
       {"idFuncionario": 2, "nome": "Ana Costa",  "cargo": "Auxiliar",       "salario": 5500},
       {"nome": "Roberto Andrade", "cargo": "Estagiário", "salario": 2500}
     ]
   }'
 WHERE d.data."_id" = 1;

-- Remover funcionário: enviar o array sem o elemento
-- Lê o ETAG atual do documento (SQL*Plus/SQLcl: variável de ligação)
BEGIN
  SELECT JSON_VALUE(d.data, '$._metadata.etag')
    INTO :etag_lido
    FROM departamentos_dv d
   WHERE d.data."_id" = 1;
END;
/

UPDATE departamentos_dv d
   SET d.data = '{
     "_id"      : 1,
     "_metadata": {"etag": "' || :etag_lido || '"},
     "nome"       : "Necropsia Especializada",
     "localizacao": "Bloco A - Térreo",
     "funcionarios": [
       {"idFuncionario": 1, "nome": "João Silva", "cargo": "Médico Legista", "salario": 16500}
     ]
   }'
 WHERE d.data."_id" = 1;

/*
Comportamento conforme anotação da tabela filha na view:
  WITH ... DELETE   : o elemento removido do array tem a linha excluída
                      (exclusão feita pela view; a FK não precisa de CASCADE).
  sem DELETE        : a regra documentada (rules-updating-duality-views) é
                      que linhas filhas NÃO são excluídas; a FK delas recebe
                      NULL (se a FK aceitar NULL). Com FK NOT NULL a operação
                      falha por violação de constraint.
                      -- A VERIFICAR: a doc descreve essa regra para exclusão
                         do objeto pai; o comportamento exato ao remover um
                         elemento do array via UPDATE não foi confirmado.
Mesmo documento alterando a MESMA linha de duas formas diferentes
(ex.: dois elementos com o mesmo idFuncionario e nomes diferentes) → erro;
para operações sobre vários documentos: ORA-42605 (cannot modify the same row
of the table more than once).
*/


--==============================================================================
-- 5. DELETE — remove o documento (linha da tabela raiz)
--==============================================================================

-- DELETE direto: não há documento enviado, logo não há verificação de ETAG
DELETE FROM departamentos_dv d WHERE d.data."_id" = 5;

-- Funcionários do departamento:
--   funcionarios WITH DELETE na view  → excluídos junto
--   funcionarios sem DELETE           → não excluídos; FK posta em NULL
--                                       (aqui a FK é NOT NULL → erro)

-- Padrão de aplicação para não excluir documento alterado por outro usuário:
-- filtrar pelo etag lido (0 linhas afetadas = documento mudou → reler).
-- Não é o mecanismo nativo de ETAG; é um predicado comum sobre o documento.
-- Lê o ETAG atual do documento (SQL*Plus/SQLcl: variável de ligação)
BEGIN
  SELECT JSON_VALUE(d.data, '$._metadata.etag')
    INTO :etag_lido
    FROM departamentos_dv d
   WHERE d.data."_id" = 4;
END;
/

DELETE FROM departamentos_dv d
 WHERE d.data."_id" = 4
   AND JSON_VALUE(d.data, '$._metadata.etag') = :etag_lido;


--==============================================================================
-- 6. Procedure padrão — UPDATE com nova tentativa em ETAG divergente
--
-- Fluxo documentado: lê o documento (com etag) → altera a cópia local com
-- JSON_TRANSFORM → grava o documento INTEIRO (que carrega o etag lido).
-- Assim há controle otimista, ao contrário de um JSON_TRANSFORM direto no
-- UPDATE. Sem concatenação de strings no JSON (evita injeção e escape).
-- A transação é do chamador (sem COMMIT aqui): ORA-42699 desfaz apenas a
-- instrução que falhou.
--==============================================================================

-- 26ai (tipo JSON em PL/SQL, duality view)
CREATE OR REPLACE PROCEDURE atualizar_nome_departamento (
  p_id_departamento  IN departamentos.id_departamento%TYPE,
  p_novo_nome        IN departamentos.nome%TYPE,
  p_max_tentativas   IN PLS_INTEGER DEFAULT 3
) IS
  co_nome_unidade CONSTANT VARCHAR2(60) := 'ATUALIZAR_NOME_DEPARTAMENTO';

  l_documento      JSON;
  l_tentativa      PLS_INTEGER := 0;

  e_etag_divergente EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_etag_divergente, -42699);
BEGIN
  <<tentativas>>
  LOOP
    l_tentativa := l_tentativa + 1;

    BEGIN
      -- 1. Leitura: documento completo com o _metadata.etag atual
      SELECT d.data
        INTO l_documento
        FROM departamentos_dv d
       WHERE d.data."_id" = p_id_departamento;

      -- 2. Alteração da cópia local (o etag lido permanece no documento)
      SELECT JSON_TRANSFORM(l_documento, SET '$.nome' = p_novo_nome)
        INTO l_documento
        FROM dual;

      -- 3. Gravação do documento inteiro → banco compara o etag
      UPDATE departamentos_dv d
         SET d.data = l_documento
       WHERE d.data."_id" = p_id_departamento;

      EXIT tentativas;
    EXCEPTION
      WHEN e_etag_divergente THEN
        IF l_tentativa >= p_max_tentativas THEN
          raise_application_error(-20100,
            co_nome_unidade || ': ' || p_max_tentativas ||
            ' tentativas falharam por ETAG divergente', TRUE);
        END IF;
        DBMS_SESSION.sleep(0.1 * l_tentativa);  -- backoff curto e crescente
    END;
  END LOOP tentativas;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    raise_application_error(-20101,
      co_nome_unidade || ': departamento não encontrado: ' || p_id_departamento);
END atualizar_nome_departamento;
/


