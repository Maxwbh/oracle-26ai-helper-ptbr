--==============================================================================
-- 1. Tabelas-base (relacionais, normalizadas)
--
-- A documentação usa GENERATED BY DEFAULT ON NULL AS IDENTITY para colunas
-- identificadoras: permite gerar a chave quando o documento não traz _id e
-- aceita _id informado. (GENERATED ALWAYS rejeitaria um _id informado.)
--==============================================================================

CREATE TABLE departamentos (
  id_departamento  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nome             VARCHAR2(100) NOT NULL,
  localizacao      VARCHAR2(100)
);

CREATE TABLE funcionarios (
  id_funcionario   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nome             VARCHAR2(100) NOT NULL,
  cargo            VARCHAR2(50),
  salario          NUMBER(10,2),
  id_departamento  NUMBER NOT NULL,
  -- FK sem ação (sem ON DELETE CASCADE/SET NULL): a exclusão em cascata,
  -- quando desejada, é declarada na duality view (anotação DELETE)
  CONSTRAINT fk_func_dept FOREIGN KEY (id_departamento)
    REFERENCES departamentos(id_departamento)
);

