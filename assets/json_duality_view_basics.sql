-- 10. Anti-patterns
--==============================================================================

/*
ANTI-PATTERN 1: Duality view sem _id no nível superior
  - _id é obrigatório: identifica a linha da tabela raiz (PK, unique ou
    identity). Sem ele a view não é válida para nenhum acesso.

ANTI-PATTERN 2: Esquecer as anotações de DML
  - Sem WITH INSERT/UPDATE/DELETE a view é somente leitura (padrão).
  - UPDATE de campo não atualizável → ORA-40940.

ANTI-PATTERN 3: Hierarquia muito profunda
  - Muitos níveis aninhados dificultam manutenção e aumentam o documento
    (e a chance de conflito de ETAG). Prefira views menores por caso de uso.

ANTI-PATTERN 4: Tentar gravar campo derivado
  - Campo calculado (ex.: salário anual) não é coluna; em 26ai use campo
    gerado (@generated), que é somente leitura. NOCHECK não resolve isso:
    NOCHECK só tira a coluna do cálculo do ETAG.

ANTI-PATTERN 5: Ignorar custo de consultas sobre arrays
  - JSON_TABLE sobre arrays grandes pode ser caro; indexe as COLUNAS das
    tabelas-base (o filtro sobre a duality view é traduzido para elas).

ANTI-PATTERN 6: FK com ON DELETE CASCADE/SET NULL em tabela dependente
  marcada DELETE
  - Na criação da view: ORA-42693 (tabela dependente não pode ser marcada
    com DELETE se a FK for RELY ou tiver ação ON DELETE).
*/
