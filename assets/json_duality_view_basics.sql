--==============================================================================
-- 8. Anotações — controle granular de DML
--==============================================================================

/*
PADRÃO: duality view é SOMENTE LEITURA. Sem anotação, vale
NOINSERT NOUPDATE NODELETE para todas as cláusulas FROM.

  WITH INSERT UPDATE DELETE        -- libera as três operações na tabela
  WITH NOINSERT NOUPDATE NODELETE  -- explícito: somente leitura
  WITH NOINSERT / NOUPDATE / NODELETE -- bloqueia operação específica
  'campo' : t.coluna WITH UPDATE   -- anotação de coluna sobrepõe a da tabela
  WITH NOCHECK                     -- coluna (ou tabela) fora do cálculo do ETAG

- Colunas identificadoras são sempre somente leitura (anotar UPDATE nelas
  gera erro).
- Coluna com NOCHECK + NOUPDATE: tentativa de alteração é IGNORADA sem erro.
- Atualizar campo NOUPDATE: ORA-40940 (Missing UPDATE annotation or NOUPDATE
  annotation specified).
- Exclusão de departamento quando a tabela filha (1:N) NÃO tem DELETE: as
  linhas filhas não são apagadas; a FK delas é posta em NULL (falha se a FK
  for NOT NULL, como aqui).
*/

-- Exemplo: departamento editável; funcionários somente leitura via esta view
-- (mudanças em funcionários são feitas em outra view ou direto na tabela)
-- sem DELETE: ver regra da FK acima
CREATE OR REPLACE JSON RELATIONAL DUALITY VIEW dept_readonly_func_dv AS
SELECT JSON {
  '_id'         : d.id_departamento,
  'nome'        : d.nome,
  'funcionarios': [
    SELECT JSON {
      'idFuncionario' : f.id_funcionario,
      'nome'          : f.nome,
      'cargo'         : f.cargo
    }
      FROM funcionarios f WITH NOINSERT NOUPDATE NODELETE  -- somente leitura
     WHERE d.id_departamento = f.id_departamento
  ]
}
  FROM departamentos d WITH INSERT UPDATE;


