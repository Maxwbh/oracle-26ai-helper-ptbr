-- 4. Consulta — SQL retorna JSON
--
-- Notação de ponto (simple dot notation) EXIGE alias de tabela.
--==============================================================================

-- Toda a hierarquia, formatada
SELECT JSON_SERIALIZE(d.data PRETTY) FROM departamentos_dv d;

-- Campos específicos via dot notation
SELECT d.data."_id", d.data.nome, d.data.localizacao
  FROM departamentos_dv d;

-- Filtro por campo
SELECT d.data
  FROM departamentos_dv d
 WHERE d.data.localizacao = 'Bloco A';

-- Desaninhar o array de funcionários (salário > 10000)
SELECT d.data.nome AS departamento,
       f.nome      AS funcionario,
       f.salario
  FROM departamentos_dv d,
       JSON_TABLE(d.data, '$.funcionarios[*]'
         COLUMNS (
           nome    VARCHAR2(100) PATH '$.nome',
           salario NUMBER        PATH '$.salario'
         )) f
 WHERE f.salario > 10000;


--==============================================================================
-- 4b. Função de tabela GRAPHQL() — consulta GraphQL direto sobre TABELAS
-- 26ai 23.26.0+  (gphql/graphql-table-function.html)
--
-- Não exige duality view: recebe a query GraphQL como string e devolve uma
-- coluna DATA do tipo JSON. Objeto aninhado é resolvido pela FK.
-- Desde 23.26.1 vírgulas no texto GraphQL são tratadas como espaço.
-- Profundidade máxima de aninhamento padrão: 10.
--==============================================================================

-- 26ai 23.26.0+
SELECT JSON_SERIALIZE(data PRETTY) AS data
  FROM GRAPHQL('
    query {
      departamentos {
        id: id_departamento
        nome
        funcionarios {
          idFuncionario: id_funcionario
          nome
          cargo
        }
      }
    }
  ');


