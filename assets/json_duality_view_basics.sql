--==============================================================================
-- 2. Duality view — sintaxe SQL
--
-- View hierárquica: departamento → array de funcionários (1:N)
-- Regras:
--   - campo _id no nível superior é OBRIGATÓRIO (mapeia a chave da tabela raiz)
--   - cada subobjeto deve ter um campo identificador da linha (idFuncionario)
--   - a ORDEM dos campos no JSON não importa (objetos JSON têm ordem indefinida)
--==============================================================================

CREATE OR REPLACE JSON RELATIONAL DUALITY VIEW departamentos_dv AS
SELECT JSON {
  '_id'        : d.id_departamento,
  'nome'       : d.nome,
  'localizacao': d.localizacao,
  'funcionarios' : [
    SELECT JSON {
      'idFuncionario' : f.id_funcionario,
      'nome'          : f.nome,
      'cargo'         : f.cargo,
      'salario'       : f.salario
    }
      FROM funcionarios f WITH INSERT UPDATE DELETE
     WHERE d.id_departamento = f.id_departamento
  ]
}
  FROM departamentos d WITH INSERT UPDATE DELETE;


--==============================================================================
-- 3. Duality view — sintaxe GraphQL (alternativa, mesma semântica)
--
-- @link(to: [...]) é OPCIONAL quando há uma única FK entre as tabelas (o join
-- é inferido). É necessário quando há mais de uma FK entre as mesmas tabelas
-- ou FK auto-referente. Os exemplos da documentação usam o nome da coluna em
-- MAIÚSCULAS dentro da string. "to" = usar a FK da tabela do objeto aninhado
-- (caso 1:N).
--==============================================================================

CREATE OR REPLACE JSON RELATIONAL DUALITY VIEW departamentos_dv_gql AS
departamentos @insert @update @delete {
  _id          : id_departamento,
  nome         : nome,
  localizacao  : localizacao,
  -- Atenção: no SQL*Plus/SQLcl uma linha que COMEÇA com "@" é executada como
  -- script. Mantenha as diretivas na mesma linha do nome do campo.
  funcionarios : funcionarios @insert @update @delete @link (to: ["ID_DEPARTAMENTO"]) [{
    idFuncionario : id_funcionario,
    nome          : nome,
    cargo         : cargo,
    salario       : salario
  }]
};

/*
Outras diretivas GraphQL documentadas para duality views em 26ai
(oracle-supported-graphql-directives-json-relational-duality-views.html):
  @array / @object   força array ou objeto único no nó seguinte
  @cast(as: id)      gera valor usável como identificador de documento
  @flex              coluna JSON como flex column
  @nest / @unnest    aninhar / achatar objetos intermediários
  @generated         campo gerado (path ou sql) — somente leitura
  @hidden            campo oculto (não aparece no documento)
  @onnull            equivalente a NULL ON NULL / ABSENT ON NULL
